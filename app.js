const $ = id => document.getElementById(id);

function safeImage(url, name) {

  return `
    <img
      src="${url}"
      alt="${name}"
      loading="lazy"
      onerror="this.style.display='none';this.parentElement.classList.add('image-fallback');"
    >
  `;

}


/* =========================================================
   VEHICLE CARD
========================================================= */

function vehicleCard(vehicle) {

  return `
    <article class="vehicle-card">

      <div class="vehicle-image">

        ${safeImage(vehicle.image, vehicle.name)}

        <div class="image-fallback-text">
          ${vehicle.name}
        </div>

      </div>

      <div class="vehicle-info">

        <span class="vehicle-tag">
          ${vehicle.tag}
        </span>

        <h3>
          ${vehicle.name}
        </h3>

        <p>
          <strong>${vehicle.year}</strong>
          • ${vehicle.generation}
        </p>

        <p>
          <strong>Engine:</strong>
          ${vehicle.engine}
        </p>

        <p>
          <strong>Power:</strong>
          ${vehicle.power}
        </p>

        <p>
          <strong>Price:</strong>
          ${vehicle.price}
        </p>

        <div class="card-buttons">

          <button
            class="details-btn"
            onclick="showDetails('${vehicle.id}')"
          >
            View Details
          </button>

          <button
            class="compare-btn"
            onclick="compareVehicle('${vehicle.id}')"
          >
            Compare
          </button>

        </div>

      </div>

    </article>
  `;
}


/* =========================================================
   DISPLAY
========================================================= */

function displayVehicles(list = vehicles) {

  const grid = $("vehicleGrid");

  const cars = list.filter(v => v.kind === "car");

  if (!cars.length) {

    grid.innerHTML = `
      <div class="no-results">
        No cars found.
      </div>
    `;

    return;
  }

  grid.innerHTML =
    cars.map(vehicleCard).join("");
}


function displayLatest() {

  const grid = $("latestGrid");

  const latest = vehicles
    .filter(v => v.kind === "car")
    .slice(0, 9);

  grid.innerHTML =
    latest.map(vehicleCard).join("");
}


function displayBikes(list = vehicles) {

  const grid = $("bikeGrid");

  const bikes = list.filter(v => v.kind === "bike");

  if (!bikes.length) {

    grid.innerHTML = `
      <div class="no-results">
        No bikes found.
      </div>
    `;

    return;
  }

  grid.innerHTML =
    bikes.map(vehicleCard).join("");
}


/* =========================================================
   SEARCH
========================================================= */

function searchVehicles() {

  const input =
    $("searchInput")
      .value
      .toLowerCase()
      .trim();

  if (!input) {

    displayVehicles();
    displayBikes();

    return;
  }

  const results =
    vehicles.filter(vehicle => {

      const text = `
        ${vehicle.name}
        ${vehicle.brand}
        ${vehicle.type}
        ${vehicle.engine}
        ${vehicle.generation}
      `.toLowerCase();

      return text.includes(input);

    });


  displayVehicles(results);
  displayBikes(results);


  document
    .getElementById("cars")
    .scrollIntoView({
      behavior: "smooth"
    });
}


function quickSearch(text) {

  $("searchInput").value = text;

  searchVehicles();
}


/* =========================================================
   BRAND FILTER
========================================================= */

function filterByBrand(brand) {

  $("searchInput").value = brand;

  const results =
    vehicles.filter(
      vehicle =>
        vehicle.brand.toLowerCase() ===
        brand.toLowerCase()
    );

  displayVehicles(results);
  displayBikes(results);

  document
    .getElementById("cars")
    .scrollIntoView({
      behavior: "smooth"
    });
}


