/* =========================================================
   COMPARE
========================================================= */

let compareList = [];


function compareVehicle(id) {

  const vehicle =
    vehicles.find(v => v.id === id);

  if (!vehicle) return;


  if (!compareList.some(v => v.id === id)) {

    compareList.push(vehicle);

  }


  if (compareList.length > 2) {

    compareList.shift();

  }


  renderCompare();


  document
    .getElementById("compare")
    .scrollIntoView({
      behavior: "smooth"
    });

}


function renderCompare() {

  const box =
    $("compareBox");


  if (!compareList.length) {

    box.innerHTML = `
      <h3>
        Vehicle comparison
      </h3>

      <p>
        Click Compare on any vehicle.
      </p>
    `;

    return;
  }


  if (compareList.length === 1) {

    const v = compareList[0];

    box.innerHTML = `

      <h3>
        ${v.name}
      </h3>

      <p>
        Add another vehicle to compare.
      </p>

      <button
        class="details-btn"
        onclick="showDetails('${v.id}')"
      >
        View Details
      </button>

    `;

    return;
  }


  const a = compareList[0];
  const b = compareList[1];


  box.innerHTML = `

    <div class="compare-table">

      <div></div>

      <strong>
        ${a.name}
      </strong>

      <strong>
        ${b.name}
      </strong>


      <span>Price</span>
      <span>${a.price}</span>
      <span>${b.price}</span>


      <span>Engine</span>
      <span>${a.engine}</span>
      <span>${b.engine}</span>


      <span>Power</span>
      <span>${a.power}</span>
      <span>${b.power}</span>


      <span>Torque</span>
      <span>${a.torque}</span>
      <span>${b.torque}</span>


      <span>Fuel</span>
      <span>${a.fuel}</span>
      <span>${b.fuel}</span>


      <span>Transmission</span>
      <span>${a.gearbox}</span>
      <span>${b.gearbox}</span>


      <span>Drive</span>
      <span>${a.drive}</span>
      <span>${b.drive}</span>

    </div>

  `;
}


