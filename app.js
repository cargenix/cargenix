/* =========================================================
   LOAD IMAGES
   ========================================================= */

async function loadImages(list) {

  for (let i = 0; i < list.length; i++) {

    const vehicle = list[i];

    const image =
      await getVehicleImage(vehicle);

    const img =
      document.getElementById(
        "vehicle-image-" + i
      );

    if (img) {
      img.src = image;
    }
  }
}


/* =========================================================
   DISPLAY CARS
   ========================================================= */

function displayVehicles(list = vehicles) {

  const grid =
    document.getElementById("vehicleGrid");

  if (!grid) return;

  if (list.length === 0) {

    grid.innerHTML =
      "<p>No cars found.</p>";

    return;
  }

  grid.innerHTML =
    list
      .map((vehicle, index) =>
        vehicleCard(vehicle, index)
      )
      .join("");

  loadImages(list);
}


/* =========================================================
   DISPLAY BIKES
   ========================================================= */

function displayBikes(list = bikes) {

  const grid =
    document.getElementById("bikeGrid");

  if (!grid) return;

  if (list.length === 0) {

    grid.innerHTML =
      "<p>No bikes found.</p>";

    return;
  }

  grid.innerHTML =
    list
      .map((vehicle, index) =>
        vehicleCard(vehicle, index + 1000)
      )
      .join("");

  loadImages(list);
}


/* =========================================================
   SEARCH
   ========================================================= */

function searchVehicles() {

  const input =
    document
      .getElementById("searchInput")
      .value
      .toLowerCase()
      .trim();

  if (!input) {

    displayVehicles();
    displayBikes();

    return;
  }

  const carResults =
    vehicles.filter(vehicle =>

      vehicle.name
        .toLowerCase()
        .includes(input) ||

      vehicle.brand
        .toLowerCase()
        .includes(input) ||

      vehicle.type
        .toLowerCase()
        .includes(input) ||

      vehicle.generation
        .toLowerCase()
        .includes(input) ||

      vehicle.version
        .toLowerCase()
        .includes(input)

    );

  const bikeResults =
    bikes.filter(vehicle =>

      vehicle.name
        .toLowerCase()
        .includes(input) ||

      vehicle.brand
        .toLowerCase()
        .includes(input) ||

      vehicle.type
        .toLowerCase()
        .includes(input) ||

      vehicle.generation
        .toLowerCase()
        .includes(input) ||

      vehicle.version
        .toLowerCase()
        .includes(input)

    );

  displayVehicles(carResults);

  displayBikes(bikeResults);

  document
    .getElementById("cars")
    .scrollIntoView({
      behavior: "smooth"
    });
}


